#
# → 스트레스 수준의 차이는 특히 자치구와 연령에서
#   상대적으로 크게 나타났다.


# ③ 스트레스가 높은 집단은 행복도 낮게 나타났는가?
#
# 스트레스가 높을수록 행복이 낮아지는
# 일관된 패턴은 나타나지 않았다.
#
# 예를 들어 10대는 스트레스체감률이 60.1%로 가장 높았지만
# 행복지수도 7.00으로 높게 나타났다.
#
# 대학원 이상 역시 스트레스체감률이 55.2%로 가장 높았지만
# 행복지수도 7.28로 높게 나타났다.
#
# → 스트레스와 행복은 단순히 반대 방향으로
#   나타나는 지표는 아니었다.


# ④ 스트레스와 행복을 함께 봤을 때 어떤 유형이 나타났는가?
