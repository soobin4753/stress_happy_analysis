#
# → 스트레스가 높은 집단이라고 해서
#   행복의 모든 영역이 낮은지 확인한다.
#
# → 고스트레스 집단에서 상대적으로 높거나 낮게 나타나는
#   행복 세부 영역의 특징을 살펴본다.
#
# ※ 행복 세부 영역의 점수가 스트레스의 원인이나
#    결과라는 의미는 아니며 집단의 특성으로 해석한다.

# 비교할 행복 세부 영역
happiness_cols = ["건강상태", "재정상태", "친지친구관계", "가정생활", "사회생활"]

# 5번의 스트레스·행복 유형 데이터에 행복 세부 영역 결합
happiness_detail = stress_happiness_type.merge(
    happiness[["구분", "구분상세"] + happiness_cols],
    on=["구분", "구분상세"],
    how="inner"
)

# 고스트레스 집단만 추출
high_stress_detail = happiness_detail[happiness_detail["스트레스수준"] == "높음"].copy()

# 분류별 분석
for group_name in analysis_groups:

    group_data = high_stress_detail[high_stress_detail["구분"] == group_name].copy()

    if group_data.empty:
        continue

    print(f"\n===== {group_name} 고스트레스 집단의 행복 세부 영역 =====")

    for _, row in group_data.iterrows():

        detail = row[happiness_cols].sort_values(ascending=False)

        highest_area = detail.index[0]
        lowest_area = detail.index[-1]

        print(f"\n{row['구분상세']} | 스트레스 {row['스트레스체감률']:.1f}% | 행복 {row['행복지수']:.2f}")
        print(detail)

        print(f"가장 높은 행복 영역 : {highest_area}, {detail[highest_area]:.2f}")
        print(f"가장 낮은 행복 영역 : {lowest_area}, {detail[lowest_area]:.2f}")

# 분석 결과:
