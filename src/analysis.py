# 질문:
# 스트레스가 특징적으로 높거나 낮은 집단은
# 행복과 여가활동에서 어떤 모습을 보이는가?
#
# 함께 비교:
# - 스트레스체감률
# - 스트레스점수
# - 행복지수
# - 주요 여가활동
#
# → 앞에서 각각 분석한 결과를 연결하여
# 특징적인 집단의 스트레스·행복·여가 특성을 종합한다.

# 분석할 여가활동 컬럼
hobby_cols = [
    "관광",
    "스포츠활동",
    "문화예술관람",
    "문화예술참여",
    "스포츠관람",
    "취미오락",
    "휴식",
    "사회기타활동",
]


# 스트레스와 여가 데이터 결합
stress_hobby = stress[
    [
        "구분",
        "구분상세",
        "스트레스체감률",
    ]
].merge(
    hobby[
        ["구분", "구분상세"] + hobby_cols
    ],
    on=["구분", "구분상세"],
    how="inner"
)

# 결과 저장
hobby_results = []

for group_name in analysis_groups:

    # 해당 기준 데이터 추출
    group_data = stress_hobby[stress_hobby["구분"] == group_name].copy()

    # 데이터가 없는 경우 건너뛰기
    if group_data.empty:
        continue

    # 해당 기준의 평균 스트레스체감률
    stress_mean = group_data["스트레스체감률"].mean()

    # 평균을 기준으로 고스트레스 / 저스트레스 분류
    group_data["스트레스수준"] = group_data["스트레스체감률"].apply(lambda x: "높음" if x >= stress_mean else "낮음")

    # 스트레스 수준별 여가활동 평균
    hobby_mean = (group_data.groupby("스트레스수준")[hobby_cols].mean().round(2))

    # 높음 / 낮음이 모두 있어야 비교 가능
    if (
        "높음" not in hobby_mean.index
        or "낮음" not in hobby_mean.index
    ):
        continue

    print(f"\n===== {group_name} 여가활동 비교 =====")
    print(hobby_mean)


    # 고스트레스 - 저스트레스 차이
    hobby_diff = (hobby_mean.loc["높음"] - hobby_mean.loc["낮음"]).round(2)

    # 차이가 큰 순서로 정렬
    hobby_diff = hobby_diff.reindex(hobby_diff.abs().sort_values(ascending=False).index)
    print("\n고스트레스 - 저스트레스 여가활동 차이")
    print(hobby_diff)

    # 결과 저장
    for hobby_name in hobby_cols:

        hobby_results.append(
            {
                "구분": group_name,
                "여가활동": hobby_name,
                "고스트레스": hobby_mean.loc[
                    "높음", hobby_name
                ],
                "저스트레스": hobby_mean.loc[
                    "낮음", hobby_name
                ],
                "차이": round(
                    hobby_mean.loc["높음", hobby_name]
                    - hobby_mean.loc["낮음", hobby_name],
                    2
                ),
            }
        )


# 전체 결과 데이터프레임
hobby_difference = pd.DataFrame(hobby_results)

# 차이의 절댓값 생성
hobby_difference["절대차이"] = (hobby_difference["차이"].abs())

# 차이가 큰 순서로 정렬
hobby_difference = hobby_difference.sort_values(by="절대차이",ascending=False,ignore_index=True)

print("\n===== 여가활동 차이가 큰 항목 =====")

