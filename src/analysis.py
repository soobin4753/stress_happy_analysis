# 7. 고스트레스 유형별 여가활동 비교
# ============================================================

# 질문:
# 스트레스는 높지만 행복 수준이 다른 집단에서 여가활동에는 어떤 차이가 나타나는가?
#
# 분석 기준:
# 성별, 연령별, 학력별, 소득별, 혼인상태별, 직업분류, 지역소분류
#
# 핵심 비교:
# 스트레스 높음 + 행복 높음 VS 스트레스 높음 + 행복 낮음
#
# 비교할 여가활동:
# 관광, 스포츠활동, 문화예술관람, 문화예술참여, 스포츠관람, 취미오락, 휴식, 사회기타활동
#
# 분석:
# - 각 분류의 고스트레스 집단 확인
# - 고행복 / 저행복 집단의 여가활동 평균 비교
# - 행복 수준에 따른 여가활동 차이 확인
#
# ※ 여가활동이 행복이나 스트레스의 원인이라고 해석하지 않는다.


hobby_cols = ["관광", "스포츠활동", "문화예술관람", "문화예술참여", "스포츠관람", "취미오락", "휴식", "사회기타활동"]

hobby_detail = stress_happiness_type.merge(hobby[["구분", "구분상세"] + hobby_cols], on=["구분", "구분상세"], how="inner")

high_stress_hobby = hobby_detail[hobby_detail["스트레스수준"] == "높음"].copy()

for group_name in analysis_groups:
    group_data = high_stress_hobby[high_stress_hobby["구분"] == group_name].copy()

    if group_data.empty:
        continue

    print(f"\n===== {group_name} 고스트레스 집단의 여가활동 =====")

    happiness_levels = group_data["행복수준"].dropna().unique()

    if not {"높음", "낮음"}.issubset(happiness_levels):
        print("고스트레스 집단에서 고행복·저행복 유형이 모두 존재하지 않아 유형 간 비교가 어렵습니다.")
        print(group_data[["구분상세", "행복수준"] + hobby_cols].to_string(index=False))
        continue

    hobby_compare = group_data.groupby("행복수준")[hobby_cols].mean().round(2)

    print("\n[행복 수준별 여가활동 평균]")
    print(hobby_compare)

    hobby_diff = (hobby_compare.loc["높음"] - hobby_compare.loc["낮음"]).round(2)
    hobby_diff = hobby_diff.reindex(hobby_diff.abs().sort_values(ascending=False).index)

    print("\n[고행복 - 저행복 여가활동 차이]")
    print(hobby_diff)

    largest_hobby = hobby_diff.abs().idxmax()

    print(f"\n여가활동 차이가 가장 큰 항목 : {largest_hobby}, {hobby_diff[largest_hobby]:+.2f}%p")

# 분석 결과:
#
# 전체 분류의 고스트레스 집단을 대상으로 여가활동을 확인한 결과,
# 성별, 연령별, 학력별, 소득별, 혼인상태별, 직업분류에서는
# 고스트레스 집단이 모두 고행복 유형으로 나타났다.
#
# 따라서 해당 분류에서는 고스트레스·고행복과
# 고스트레스·저행복 집단 간 여가활동 비교가 어려웠다.
#
# 반면 지역소분류에서는 두 유형이 모두 나타나
# 행복 수준에 따른 여가활동 차이를 비교할 수 있었다.
#
# 고스트레스·고행복 자치구는 저행복 자치구보다
# 사회기타활동이 5.96%p, 관광이 3.54%p 높게 나타났다.
#
# 반면 고스트레스·저행복 자치구는
# 휴식이 3.71%p, 취미오락과 스포츠관람이 각각 3.54%p 높았다.
#
# → 고스트레스 집단이라고 해서 모두 행복이 낮은 것은 아니었으며,
#   대부분의 분류에서는 오히려 고스트레스 집단이 고행복 유형으로 나타났다.
#
# → 고스트레스·고행복과 고스트레스·저행복이 모두 존재한 자치구에서는
#   행복 수준에 따라 여가활동 구성에 차이가 나타났다.
#
# ※ 여가활동이 행복이나 스트레스의 원인이라는 의미는 아니다.

