# 직업별로는 화이트칼라(48.0%),
# 자치구별로는 강남구(58.9%)의
# 스트레스체감률이 가장 높게 나타났다.


# ② 어떤 특성에서 스트레스 격차가 가장 크게 나타났는가?
#
# 자치구별 스트레스 격차가 35.2%p로 가장 크게 나타났으며,
# 연령별 격차가 23.5%p로 그 뒤를 이었다.
