import pandas as pd

happiness = pd.read_csv("data/processed/happiness_processed.csv")
hobby = pd.read_csv("data/processed/hobby_processed.csv")
stress = pd.read_csv("data/processed/stress_processed.csv")
worry = pd.read_csv("data/processed/worry_processed.csv")

# ============================================================
# 전체 분석 흐름
# ============================================================

# 주제:
# 서울시민의 집단별 스트레스 격차와 생활 특성 분석
#
# 핵심 질문:
# 어떤 집단에서 스트레스가 높게 나타나며,
# 그 집단은 고민·행복·여가 측면에서 어떤 특징을 보이는가?

# ============================================================
# 1. 집단별 스트레스 수준 분석
# ============================================================

# 질문:
# 어떤 집단에서 스트레스가 높게 나타나는가?
#
# 분석 기준:
# 성별, 연령별, 학력별, 소득별, 혼인상태별, 직업분류, 지역소분류
#
# 분석:
# - 집단별 스트레스체감률 비교
# - 스트레스가 가장 높은 집단 확인
# - 스트레스가 가장 낮은 집단 확인
#
# → 스트레스가 상대적으로 높은 집단을 찾는다.

# 분석할 구분
analysis_groups = ["성별", "연령별", "학력별", "소득별", "혼인상태별", "직업분류", "지역소분류"]

for group_name in analysis_groups:

    # 해당 구분의 데이터만 추출
    group_data = stress[stress["구분"] == group_name][["구분상세", "스트레스체감률", "스트레스점수"]].copy()

    # 데이터가 없는 경우 건너뛰기
    if group_data.empty:
        continue

    # 스트레스체감률이 높은 순서대로 정렬
    group_data = group_data.sort_values(by="스트레스체감률", ascending=False, ignore_index=True)

    print(f"\n===== {group_name} =====")
    print(group_data)

    # 스트레스체감률이 가장 높은 / 낮은 집단
    highest = group_data.iloc[0]
    lowest = group_data.iloc[-1]

    print(f"\n스트레스체감률이 가장 높은 집단 : {highest['구분상세']}, {highest['스트레스체감률']:.1f}%")
    print(f"스트레스체감률이 가장 낮은 집단 : {lowest['구분상세']}, {lowest['스트레스체감률']:.1f}%")

# 분석 결과:
#
# 집단별 스트레스체감률을 비교한 결과,
# 연령에서는 10대(60.1%), 학력에서는 대학원 이상(55.2%),
# 소득에서는 600~800만원 미만(49.0%), 직업에서는 화이트칼라(48.0%)가 가장 높았다.
#
# 자치구에서는 강남구가 58.9%로 가장 높았고,
# 중랑구는 23.7%로 가장 낮아 지역별 차이가 크게 나타났다.
#
# → 스트레스는 집단에 따라 뚜렷한 차이를 보였으며,
#   특히 연령과 지역에서 큰 격차가 나타났다.
#
# → 다음 분석에서는 어떤 분류 기준에서
#   스트레스 격차가 가장 큰지 확인한다.


# ============================================================
# 2. 집단별 스트레스 격차 분석
# ============================================================

# 질문:
# 어떤 특성에서 집단 간 스트레스 차이가 크게 나타나는가?
#
# 분석:
# - 각 기준별 최고 스트레스체감률
# - 각 기준별 최저 스트레스체감률
# - 최고 - 최저 격차(%p) 계산
#
# → 성별, 연령, 학력, 소득, 직업, 지역 등 중
#   어디에서 스트레스 격차가 특히 크게 나타나는지 확인한다.
#
# → 이후 분석에서 주목할 집단을 선정한다.

gap_results = []

for group_name in analysis_groups:
    group_data = stress[stress["구분"] == group_name][["구분상세", "스트레스체감률"]].copy()

    if group_data.empty:
        continue

    highest = group_data.loc[group_data["스트레스체감률"].idxmax()]
    lowest = group_data.loc[group_data["스트레스체감률"].idxmin()]
    gap = round(highest["스트레스체감률"] - lowest["스트레스체감률"], 1)

    gap_results.append({
        "구분": group_name,
        "최고집단": highest["구분상세"],
        "최고체감률": highest["스트레스체감률"],
        "최저집단": lowest["구분상세"],
        "최저체감률": lowest["스트레스체감률"],
        "격차": gap
    })


stress_gap = pd.DataFrame(gap_results).sort_values(by="격차", ascending=False, ignore_index=True)

print("\n===== 집단별 스트레스 격차 =====")
print(stress_gap)

largest_gap = stress_gap.iloc[0]

print(f"\n스트레스 격차가 가장 큰 기준 : {largest_gap['구분']}, {largest_gap['격차']:.1f}%p")

# 분석 결과:
#
# 스트레스 격차는 자치구에서 35.2%p로 가장 크게 나타났으며,
# 연령(23.5%p), 학력(15.0%p)이 뒤를 이었다.
#
# 반면 성별 격차는 4.6%p로 가장 작았다.
#
# → 스트레스 차이는 성별보다 지역과 연령에서 더 크게 나타났다.
# → 이후 지역·연령 등 격차가 큰 집단을 중심으로
#   개인적 고민과 생활 특성을 살펴본다.

# ============================================================
# 3. 고스트레스 집단의 개인적 고민 특성 분석
# ============================================================

# 질문:
# 스트레스가 높게 나타난 집단에서는
# 과거 어떤 고민이 상대적으로 두드러졌는가?
#
# 분석:
# - 1~2단계에서 확인한 주요 고스트레스 집단 중심
# - 경제문제, 건강, 자녀양육, 노후생활, 가족문제, 공부, 진로, 자기개발, 대인관계 등의 고민 비율 비교
#
# - 집단별 주요 고민 TOP 5 확인
#
# → 고스트레스 집단에서 나타났던
#   고민 특성을 참고적으로 살펴본다.
#
# ※ 고민 데이터는 과거 자료이므로
#   현재 스트레스의 원인으로 해석하지 않는다.

# 분석할 고민 항목
worry_cols = ["경제문제", "건강", "자녀양육", "노후생활", "가족문제", "공부", "진로", "결혼", "자기개발", "이성우정", "신체외모", "인터넷커뮤니티", "학교폭력", "기타"]

# 고민 데이터와 공통으로 분석 가능한 구분
worry_groups = [group for group in analysis_groups if group in worry["구분"].unique()]

for group_name in worry_groups:

    # 해당 기준에서 스트레스가 가장 높은 집단
    stress_group = stress[stress["구분"] == group_name].sort_values(by="스트레스체감률", ascending=False)

    if stress_group.empty:
        continue

    high_group = stress_group.iloc[0]["구분상세"]
    high_stress = stress_group.iloc[0]["스트레스체감률"]

    # 같은 집단의 고민 데이터 조회
    worry_group = worry[(worry["구분"] == group_name) & (worry["구분상세"] == high_group)]

    if worry_group.empty:
        continue

    # 고민 TOP 5
    top5 = worry_group[worry_cols].iloc[0].dropna().sort_values(ascending=False).head(5)

    print(f"\n===== {group_name} : {high_group} =====")
    print(f"스트레스체감률 : {high_stress:.1f}%")
    print("과거 주요 고민 TOP 5")
    print(top5)

# 분석 결과:
#
# 고스트레스 집단의 과거 고민을 살펴본 결과,
# 집단에 따라 주요 고민의 유형이 다르게 나타났다.
#
# 특히 10대는 공부(54.5%)가 압도적으로 높았고,
# 미혼은 공부(22.2%)와 진로(16.4%) 고민이 두드러졌다.
#
# 반면 남성과 대학원 이상에서는 경제문제가 가장 높았으며,
# 강남구에서는 건강(19.5%)과 경제문제(18.1%)가 주요 고민으로 나타났다.
#
# → 고스트레스 집단이라고 해서 동일한 고민을 보이는 것이 아니라,
#   집단의 특성에 따라 두드러지는 고민이 달랐다.
#
# ※ 과거 고민 자료이므로 현재 스트레스의 원인으로 해석하지 않는다.


# ============================================================
# 4. 스트레스와 행복 수준 비교
# ============================================================

# 질문:
# 스트레스가 높은 집단은 행복도 낮게 나타나는가?
#
# 분석:
# - 집단별 스트레스체감률과 행복지수 비교
# - 고스트레스 집단의 행복지수 확인
# - 저스트레스 집단의 행복지수 확인
# - 예상과 다른 집단 확인
#
# → 스트레스가 높으면 행복이 낮다는
#   단순한 관계가 실제로 나타나는지 확인한다.

# 스트레스와 행복 데이터 결합
stress_happiness = stress[["구분", "구분상세", "스트레스체감률"]].merge(happiness[["구분", "구분상세", "행복지수"]], on=["구분", "구분상세"], how="inner")

for group_name in analysis_groups:
    group_data = stress_happiness[stress_happiness["구분"] == group_name][["구분상세", "스트레스체감률", "행복지수"]].copy()

    if group_data.empty:
        continue

    # 스트레스체감률이 높은 순서대로 정렬
    group_data = group_data.sort_values(by="스트레스체감률", ascending=False, ignore_index=True)

    # 고스트레스 / 저스트레스 집단
    highest = group_data.iloc[0]
    lowest = group_data.iloc[-1]

    print(f"\n===== {group_name} 스트레스·행복 비교 =====")
    print(group_data)

    print(f"\n고스트레스 집단 : {highest['구분상세']} | 스트레스 {highest['스트레스체감률']:.1f}% | 행복 {highest['행복지수']:.2f}")
    print(f"저스트레스 집단 : {lowest['구분상세']} | 스트레스 {lowest['스트레스체감률']:.1f}% | 행복 {lowest['행복지수']:.2f}")

# 분석 결과:
#
# 스트레스가 가장 높은 집단이 반드시 행복이 낮은 것은 아니었다.
#
# 특히 10대는 스트레스체감률이 60.1%로 연령 중 가장 높았지만
# 행복지수도 7.00으로 높게 나타났다.
#
# 학력에서도 대학원 이상은 스트레스가 가장 높으면서(55.2%)
# 행복지수도 7.28로 가장 높았다.
#
# 반대로 60세 이상과 200만원 미만 집단은
# 스트레스는 가장 낮았지만 행복지수 역시 가장 낮았다.
#
# → 스트레스와 행복은 단순히 반대 방향으로 나타나지 않았다.
# → 따라서 다음 분석에서는 스트레스와 행복을 함께 고려해
#   집단을 유형화하고 그 특징을 비교한다.

# ============================================================
# 5. 스트레스·행복 유형 분석
# ============================================================

# 질문:
# 스트레스와 행복을 함께 보면
# 집단들은 어떤 유형으로 나타나는가?
#
# 유형:
# - 스트레스 높음 + 행복 높음
# - 스트레스 높음 + 행복 낮음
# - 스트레스 낮음 + 행복 높음
# - 스트레스 낮음 + 행복 낮음
#
# 분석:
# - 각 분류 안의 평균을 기준으로 높음 / 낮음 구분
# - 각 집단의 스트레스·행복 유형 생성
#
# → 같은 고스트레스 집단 안에서도
#   행복 수준이 다르게 나타나는 집단을 찾는다.

type_results = []

for group_name in analysis_groups:
    group_data = stress_happiness[stress_happiness["구분"] == group_name].copy()

    if group_data.empty:
        continue

    # 해당 분류의 스트레스·행복 평균
    stress_mean = group_data["스트레스체감률"].mean()
    happiness_mean = group_data["행복지수"].mean()

    # 평균을 기준으로 높음 / 낮음 분류
    group_data["스트레스수준"] = group_data["스트레스체감률"].apply(lambda x: "높음" if x >= stress_mean else "낮음")
    group_data["행복수준"] = group_data["행복지수"].apply(lambda x: "높음" if x >= happiness_mean else "낮음")

    # 스트레스·행복 유형 생성
    group_data["스트레스행복유형"] = "스트레스 " + group_data["스트레스수준"] + " + 행복 " + group_data["행복수준"]

    type_results.append(group_data)

# 전체 유형 데이터 결합
stress_happiness_type = pd.concat(type_results, ignore_index=True)

# 분류별 결과 확인
for group_name in analysis_groups:
    result = stress_happiness_type[stress_happiness_type["구분"] == group_name][["구분상세", "스트레스체감률", "행복지수", "스트레스행복유형"]]

    if result.empty:
        continue

    print(f"\n===== {group_name} 스트레스·행복 유형 =====")
    print(result)

# 유형별 집단 수
type_count = stress_happiness_type["스트레스행복유형"].value_counts()

print("\n===== 스트레스·행복 유형별 집단 수 =====")
print(type_count)

# 고스트레스 집단만 확인
high_stress = stress_happiness_type[stress_happiness_type["스트레스수준"] == "높음"]

print("\n===== 고스트레스 집단 =====")
print(high_stress[["구분", "구분상세", "스트레스체감률", "행복지수", "스트레스행복유형"]])

# 분석 결과:
#
# 스트레스와 행복을 함께 유형화한 결과,
# '스트레스 높음 + 행복 높음' 유형이 18개로 가장 많았다.
#
# 특히 10대, 대학원 이상, 미혼 등은
# 스트레스가 높은 동시에 행복도 높은 유형으로 나타났다.
#
# 반면 고스트레스·저행복 유형은 5개였으며,
# 용산구, 동대문구, 강북구, 관악구, 강동구가 해당됐다.
#
# → 스트레스가 높은 집단에서도 행복 수준은 다르게 나타났다.
#
# → 다음 분석에서는 고스트레스 집단의 행복을 세부 영역으로 나누어
#   어떤 영역에서 높고 낮은 특징이 나타나는지 확인한다.

# ============================================================
# 6. 고스트레스 집단의 행복 세부 영역 분석
# ============================================================

# 질문:
# 스트레스가 높게 나타난 집단에서는
# 어떤 행복 영역의 점수가 높거나 낮게 나타나는가?
#
# 분석 기준:
# 성별, 연령별, 학력별, 소득별, 혼인상태별, 직업분류, 지역소분류 
#
# 비교할 행복 영역:
