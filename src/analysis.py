import pandas as pd

happiness = pd.read_csv("data/processed/happiness_processed.csv")
hobby = pd.read_csv("data/processed/hobby_processed.csv")
stress = pd.read_csv("data/processed/stress_processed.csv")

# ============================================================
# 전체 분석 흐름
# ============================================================

# 분석 목적:
#
# 서울시민의 스트레스 수준이 집단별로 어떻게 다르게 나타나는지 확인하고,
# 스트레스가 높은 집단의 행복 수준과 여가활동 특성을 함께 비교한다.
#
# 이를 통해 어떤 집단에서 스트레스가 상대적으로 높게 나타나는지,
# 어떤 특성에서 스트레스 격차가 크게 나타나는지,
# 고스트레스 집단과 저스트레스 집단의 생활 특성에는
# 어떤 차이가 있는지 확인한다.


# ============================================================
# 1. 집단별 스트레스 수준 분석
# ============================================================

# 질문:
# 어떤 집단에서 스트레스가 높게 나타나는가?
#
# 분석 기준:
# - 성별
# - 연령별
# - 학력별
# - 소득별
# - 혼인상태별
# - 직업분류
# - 지역별
#
# 분석:
# - 각 기준별 스트레스체감률 비교
# - 스트레스체감률이 가장 높은 집단 확인
# - 스트레스체감률이 가장 낮은 집단 확인
#
# → 서울시 통계에서 상대적으로 스트레스가 높은 집단을 찾는다.

# 분석할 구분
analysis_groups = [
    "성별",
    "연령별",
    "학력별",
    "소득별",
    "혼인상태별",
    "직업분류",
    "지역소분류",
]


for group_name in analysis_groups:

    # 해당 구분의 데이터만 추출
    group_data = stress[stress["구분"] == group_name][["구분상세","스트레스체감률","스트레스점수"]].copy()

    # 스트레스체감률이 높은 순서대로 정렬
    group_data = group_data.sort_values(by="스트레스체감률",ascending=False,ignore_index=True)

    # 데이터가 없는 경우 건너뛰기
    if group_data.empty:
        continue

    print(f"\n===== {group_name} =====")
    print(group_data)

    # 스트레스체감률이 가장 높은 집단
    highest = group_data.iloc[0]

    # 스트레스체감률이 가장 낮은 집단
    lowest = group_data.iloc[-1]

    print(f"스트레스체감률이 가장 높은 집단 : {highest['구분상세']}, {highest['스트레스체감률']:.1f}%")
    print(f"스트레스체감률이 가장 낮은 집단 : {lowest['구분상세']}, {lowest['스트레스체감률']:.1f}%")

# 분석 결과:
#
# 집단별 스트레스체감률을 비교한 결과,
# 자치구별 차이가 가장 크게 나타났다.
#
# 강남구는 58.9%로 가장 높고,
# 중랑구는 23.7%로 가장 낮아 35.2%p의 차이가 나타났다.
#
# 연령별로는 10대가 60.1%로 가장 높고,
# 60세 이상이 36.6%로 가장 낮아 23.5%p 차이가 나타났다.
#
# 학력별로는 대학원 이상이 55.2%로 가장 높았고,
# 소득별로는 600~800만원 미만이 49.0%로 가장 높게 나타났다.
#
# 반면 성별 차이는 남성 46.3%, 여성 41.7%로
# 다른 특성에 비해 상대적으로 작았다.
#
# → 서울시 통계에서는 스트레스 수준이 집단별로 동일하지 않았으며,
#   특히 지역과 연령에서 큰 차이가 나타났다.

# ============================================================
# 2. 집단별 스트레스 격차 분석
# ============================================================

# 질문:
# 어떤 특성에서 집단 간 스트레스 차이가 크게 나타나는가?
#
# 분석:
# - 각 기준별 최고 스트레스체감률 확인
# - 각 기준별 최저 스트레스체감률 확인
# - 최고값 - 최저값으로 스트레스 격차 계산
#
# 예:
# 성별 격차
# 연령별 격차
# 소득별 격차
# 직업별 격차
# 자치구별 격차
#
# → 스트레스 수준의 차이가 특히 크게 나타나는 특성을 확인한다.

gap_results = []

for group_name in analysis_groups:

    # 해당 구분의 데이터만 추출
    group_data = stress[stress["구분"] == group_name][["구분상세", "스트레스체감률"]].copy()

    # 데이터가 없는 경우 건너뛰기
    if group_data.empty:
        continue

    # 스트레스체감률이 가장 높은 집단
    highest = group_data.loc[group_data["스트레스체감률"].idxmax()]

    # 스트레스체감률이 가장 낮은 집단
    lowest = group_data.loc[group_data["스트레스체감률"].idxmin()]

    # 최고 - 최저 격차 계산
    gap = (highest["스트레스체감률"]- lowest["스트레스체감률"])

    # 결과 저장
    gap_results.append(
        {
            "구분": group_name,
            "최고집단": highest["구분상세"],
            "최고체감률": highest["스트레스체감률"],
            "최저집단": lowest["구분상세"],
            "최저체감률": lowest["스트레스체감률"],
            "격차": round(gap, 1),
        }
    )


# 데이터프레임으로 변환
stress_gap = pd.DataFrame(gap_results)

# 격차가 큰 순서대로 정렬
stress_gap = stress_gap.sort_values(by="격차",ascending=False,ignore_index=True)
print(f"집단별 스트레스 격차 : \n {stress_gap}")

# 스트레스 격차가 가장 큰 기준
largest_gap = stress_gap.iloc[0]
print(f"스트레스 격차가 가장 큰 기준 : {largest_gap['구분']},  {largest_gap['격차']:.1f}%p")

# 분석 결과:
#
# 집단별 스트레스체감률의 격차를 비교한 결과,
# 자치구별 격차가 35.2%p로 가장 크게 나타났고,
# 연령별 격차가 23.5%p로 그 뒤를 이었다.
#
# 반면 성별 격차는 4.6%p로 가장 작게 나타났다.
#
# → 스트레스체감률의 차이는 분류 기준에 따라 달랐으며,
#   특히 자치구와 연령에서 상대적으로 큰 격차가 확인되었다.
#
# → 이후 스트레스가 높은 집단의 행복 수준과
#   여가활동 특성을 함께 비교한다.

# ============================================================
# 3. 스트레스와 행복 수준 비교
# ============================================================

# 질문:
# 스트레스가 높은 집단은 행복 수준도 낮게 나타나는가?
#
# 분석:
# - 집단별 스트레스체감률과 행복지수 비교
# - 스트레스가 높은 집단의 행복지수 확인
# - 스트레스가 낮은 집단의 행복지수 확인
#
# → 높은 스트레스와 낮은 행복이 항상 함께 나타나는지 확인한다.
#
# → 예상과 다른 결과를 보이는 집단도 함께 확인한다.

# 스트레스와 행복 데이터 결합
stress_happiness = stress[["구분","구분상세","스트레스체감률","스트레스점수",]].merge(
    happiness[["구분","구분상세","행복지수",]],on=["구분", "구분상세"],how="inner")

for group_name in analysis_groups:
    # 해당 기준의 데이터만 추출
    group_data = stress_happiness[stress_happiness["구분"] == group_name][["구분상세","스트레스체감률","행복지수",]].copy()

    # 데이터가 없는 경우 건너뛰기
    if group_data.empty:
        continue

    # 스트레스체감률이 높은 순으로 정렬
    group_data = group_data.sort_values(by="스트레스체감률",ascending=False,ignore_index=True)
    print(f"{group_name} 스트레스·행복 : \n {group_data}")

    # 스트레스가 가장 높은 집단
    highest_stress = group_data.iloc[0]

    # 스트레스가 가장 낮은 집단
    lowest_stress = group_data.iloc[-1]

    print(
        f"\n스트레스가 가장 높은 집단 : "
        f"{highest_stress['구분상세']}, "
        f"스트레스 {highest_stress['스트레스체감률']:.1f}%, "
        f"행복지수 {highest_stress['행복지수']:.2f}"
    )

    print(
        f"스트레스가 가장 낮은 집단 : "
        f"{lowest_stress['구분상세']}, "
        f"스트레스 {lowest_stress['스트레스체감률']:.1f}%, "
        f"행복지수 {lowest_stress['행복지수']:.2f}"
    )

# 분석 결과:
#
# 스트레스가 높은 집단과 낮은 집단의 행복지수를 비교한 결과,
# 스트레스가 높을수록 행복이 낮아지는 일관된 패턴은 나타나지 않았다.
#
# 연령별로는 스트레스가 가장 높은 10대(60.1%)의 행복지수가 7.00으로,
# 스트레스가 가장 낮은 60세 이상(36.6%)의 6.19보다 높았다.
#
# 학력별에서도 대학원 이상은 스트레스체감률이 55.2%로 가장 높았지만
# 행복지수 역시 7.28로 높게 나타났다.
#
# 소득별에서도 스트레스가 가장 높은 600~800만원 미만의 행복지수는 6.85,
# 스트레스가 가장 낮은 200만원 미만은 5.76으로 나타났다.
#
# 자치구별로는 스트레스가 가장 높은 강남구(58.9%)와
# 가장 낮은 중랑구(23.7%)의 행복지수가 각각 6.66, 6.58로 큰 차이가 없었다.
#
# → 스트레스체감률과 행복지수는 단순히 반대 방향으로 움직이지 않았으며,
#   높은 스트레스와 높은 행복이 동시에 나타나는 집단도 확인되었다.

# ============================================================
# 4. 스트레스·행복 유형 분석
# ============================================================

# 질문:
# 스트레스와 행복을 함께 봤을 때
# 집단들은 어떤 특징을 보이는가?
#
# 유형:
# - 스트레스 높음 + 행복 높음
# - 스트레스 높음 + 행복 낮음
# - 스트레스 낮음 + 행복 높음
# - 스트레스 낮음 + 행복 낮음
#
# → 단순히 스트레스가 높은 집단만 보는 것이 아니라
# 스트레스와 행복이 함께 나타나는 패턴을 확인한다.
#
# → 특히 예상과 다른 특징을 보이는 집단을 찾는다.

# 결과를 저장할 리스트
type_results = []


for group_name in analysis_groups:

    # 해당 기준의 데이터만 추출
    group_data = stress_happiness[stress_happiness["구분"] == group_name].copy()

    # 데이터가 없는 경우 건너뛰기
    if group_data.empty:
        continue

    # 해당 분류의 스트레스체감률 평균
    stress_mean = group_data["스트레스체감률"].mean()

    # 해당 분류의 행복지수 평균
    happiness_mean = group_data["행복지수"].mean()

    # 스트레스 높음 / 낮음 분류
    group_data["스트레스수준"] = group_data["스트레스체감률"].apply(lambda x: "높음" if x >= stress_mean else "낮음")

    # 행복 높음 / 낮음 분류
    group_data["행복수준"] = group_data["행복지수"].apply(lambda x: "높음" if x >= happiness_mean else "낮음")

    # 스트레스 + 행복 유형 생성
    group_data["스트레스행복유형"] = (
        "스트레스 "
        + group_data["스트레스수준"]
        + " + 행복 "
        + group_data["행복수준"]
    )
    print(f"{group_name} 스트레스·행복 유형")
    print(group_data[[
                "구분상세",
                "스트레스체감률",
                "행복지수",
                "스트레스행복유형",
            ]
        ].sort_values(
            by="스트레스체감률",
            ascending=False,
            ignore_index=True
        )
    )


    # 전체 결과 저장
    type_results.append(
        group_data[
            [
                "구분",
                "구분상세",
                "스트레스체감률",
                "행복지수",
                "스트레스행복유형",
            ]
        ]
    )


# 모든 분류 결과 하나로 합치기
stress_happiness_type = pd.concat(type_results, ignore_index=True)

# 유형별 개수 확인
type_count = (stress_happiness_type["스트레스행복유형"].value_counts())
print(f"스트레스·행복 유형별 집단 수 {type_count}")

# 예상과 다른 특징:
# 스트레스가 높으면서 행복도 높은 집단 확인
high_stress_high_happiness = stress_happiness_type[
    stress_happiness_type["스트레스행복유형"]
    == "스트레스 높음 + 행복 높음"
].copy()
print("\n===== 스트레스 높음 + 행복 높음 집단 =====")
print(
    high_stress_high_happiness[
        [
            "구분",
            "구분상세",
            "스트레스체감률",
            "행복지수",
        ]
    ]
)

# 분석 결과:
#
# 스트레스와 행복을 평균 기준으로 유형화한 결과,
# '스트레스 높음 + 행복 높음' 유형이 18개로 가장 많이 나타났다.
#
# 반면 '스트레스 높음 + 행복 낮음' 유형은 5개로 가장 적었다.
#
# 연령별로는 10대·30대·40대가
# '스트레스 높음 + 행복 높음' 유형으로 나타났으며,
# 학력별 대학원 이상, 소득별 600~800만원 미만,
# 직업별 화이트칼라도 같은 유형으로 나타났다.
#
# 자치구에서도 강남구·서대문구·마포구 등은
# 스트레스와 행복이 모두 높은 유형으로 나타난 반면,
# 동대문구·강북구·강동구·관악구·용산구는
# 스트레스는 높지만 행복은 낮은 유형으로 나타났다.
#
# → 스트레스가 높으면 행복이 낮을 것이라는 예상과 달리,
#   높은 스트레스와 높은 행복이 함께 나타나는 집단이 다수 확인되었다.
#
# → 따라서 스트레스와 행복은 단순히 반대되는 지표로 보기 어려우며,
#   같은 고스트레스 집단 안에서도 행복 수준에 차이가 나타났다.
#
# → 다음으로 이러한 집단 간 차이가
#   여가활동에서도 나타나는지 비교한다.

# ============================================================
# 5. 고스트레스·저스트레스 집단의 여가활동 비교
# ============================================================

# 질문:
# 스트레스가 높은 집단과 낮은 집단의
